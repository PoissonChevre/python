# while
i=3
while i != 0:
    print("meow2")
    i = i - 1
    
# incrémentation
i=0
while i < 3:
    print("meow3")
    i += 1
    
# for
for i in [0, 1, 2]:
    print("meow4")

# for better 
for i in range(3):
    print("meow5")

# pythonesque _ underscore
for _ in range(3):
    print("meow6")
    
# pythonesque minimal
print("meow7\n" * 3, end="")

